function getBuenosAiresDateString(offsetDays = 0) {
  const now = new Date();
  const baNow = new Date(
    now.toLocaleString('en-US', { timeZone: 'America/Argentina/Buenos_Aires' })
  );
  baNow.setDate(baNow.getDate() + offsetDays);
  const y = baNow.getFullYear();
  const m = String(baNow.getMonth() + 1).padStart(2, '0');
  const d = String(baNow.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

function getNextOpenDates(count = 4) {
  const dates = [];
  let offset = 0;
  while (dates.length < count && offset < 21) {
    const dateStr = getBuenosAiresDateString(offset);
    const [y, m, d] = dateStr.split('-').map(Number);
    const dow = new Date(y, m - 1, d).getDay(); // 0=Dom, 1=Lun
    if (dow >= 2 && dow <= 6) {
      dates.push(dateStr);
    }
    offset++;
  }
  return dates;
}

